import type { AnyField } from "./schema/fields.ts";
import type { Model } from "./schema/model.ts";

const pascal = (s: string) => s.replace(/(^|[_-])([a-z0-9])/g, (_, __, c: string) => c.toUpperCase());
const RESERVED = new Set(["Block", "Media", "Schema"]);
const quote = (key: string) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key));

function tsType(f: AnyField, indent: string): string {
  const o = f.options;
  switch (f.kind) {
    case "number": return "number";
    case "boolean": return "boolean";
    case "enum": return (o.values as string[]).map((v) => JSON.stringify(v)).join(" | ");
    case "ref": return o.many ? "string[]" : "string";
    case "blocks": return "Block[]";
    case "media": return "Media";
    case "json": return "unknown";
    case "list": return "string[]";
    case "object": return objectType(o.fields as Record<string, AnyField>, indent);
    default: return "string";
  }
}

function objectType(fields: Record<string, AnyField>, indent: string): string {
  const inner = indent + "  ";
  const lines = Object.entries(fields).map(([key, f]) => {
    const doc = f.options.description ? `${inner}/** ${String(f.options.description).replace(/\*\//g, "* /")} */\n` : "";
    return `${doc}${inner}${quote(key)}${f.options.required ? "" : "?"}: ${tsType(f, inner)};`;
  });
  return `{\n${lines.join("\n")}\n${indent}}`;
}

/**
 * TypeScript types for a client in another repository: one interface per model
 * plus a `Schema` map for `createClient<Schema>()`. Shapes match what REST returns
 * (block fields as blocks).
 */
export function generateTypes(models: Model[], site: string): string {
  const names = new Map(models.map((m) => [m.name, RESERVED.has(pascal(m.name)) ? `${pascal(m.name)}Entry` : pascal(m.name)]));
  const out = [
    `// Generated by \`aicms types\` from the models of "${site}". Do not edit; run it again after changing a model.`,
    "",
    "export interface Block {",
    "  type: string;",
    "  [key: string]: unknown;",
    "}",
    "",
    "export interface Media {",
    "  url: string;",
    "  alt?: string;",
    "  width?: number;",
    "  height?: number;",
    "}",
  ];
  for (const m of models) {
    out.push("", ...(m.label || m.description ? [`/** ${[m.label, m.description].filter(Boolean).join(": ")} */`] : []));
    out.push(`export interface ${names.get(m.name)} ${objectType(m.fields, "")}`);
  }
  out.push("", "export interface Schema {", ...models.map((m) => `  ${m.name}: ${names.get(m.name)};`), "}", "");
  return out.join("\n");
}
